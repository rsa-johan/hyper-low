//! C99 header generator. All functions are `static inline`, so no companion `.c` file is needed.

use std::fmt::Write;

use super::Layout;
use crate::tools::{
    ast::Literal,
    resolve::{Chunk, DefIr, EnumIr, FieldIr, FieldTy, FilterIr, FnIr, FrameIr, Model, Prim, Slot},
    syntax::to_upper_snake,
};

pub fn generate(model: &Model, source: &str, unit: &str, layout: &Layout) -> String {
    let guard_name = match layout {
        Layout::Standalone => unit.to_string(),
        Layout::Unit { pkg, .. } => format!("{pkg}_{unit}"),
    };
    let guard = format!("PROTO_C_{}_H", to_upper_snake(&guard_name).replace(|c: char| !c.is_ascii_alphanumeric(), "_"));
    let mut o = String::new();
    let _ = writeln!(o, "/* @generated by proto_c from `{source}`. Do not edit. */");
    let _ = writeln!(o, "#ifndef {guard}\n#define {guard}\n");
    o.push_str(PRELUDE);
    if let Layout::Unit { c_includes, .. } = layout {
        o.push('\n');
        for inc in *c_includes {
            let _ = writeln!(o, "#include \"{inc}.h\"");
        }
    }
    gen_specs(&mut o, model, unit);
    for e in model.enums.iter().filter(|e| !e.external) {
        gen_enum(&mut o, e);
    }
    for d in model.defs.iter().filter(|d| !d.external) {
        gen_def(&mut o, model, d);
    }
    for f in model.frames.iter().filter(|f| !f.external) {
        gen_frame(&mut o, f, model);
    }
    for f in model.fns.iter().filter(|f| !f.external) {
        gen_fn(&mut o, f, model);
    }
    let _ = writeln!(o, "\n#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");
    o
}

const PRELUDE: &str = "#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#ifdef __cplusplus
extern \"C\" {
#endif

#ifndef PROTO_C_STATUS_DEFINED
#define PROTO_C_STATUS_DEFINED
#define PROTO_C_OK 0
#define PROTO_C_ERR_SHORT_BUFFER (-1)
#define PROTO_C_ERR_INVALID_ENUM (-2)
#endif
";

fn lit(l: Literal, ty: Prim) -> String {
    match l {
        Literal::Int(v) if v < 0 => format!("({v}LL)"),
        Literal::Int(v) if v > i128::from(u32::MAX) => format!("{v}ULL"),
        Literal::Int(v) => format!("{v}u"),
        Literal::Float(f) if ty == Prim::F32 => format!("{:?}f", f as f32),
        Literal::Float(f) => format!("{f:?}"),
        Literal::Bool(b) => b.to_string(),
    }
}

fn gen_specs(o: &mut String, model: &Model, unit: &str) {
    let prefix = to_upper_snake(unit);
    let specs: Vec<_> = model.specs.iter().filter(|s| !s.external).collect();
    if !specs.is_empty() {
        o.push('\n');
    }
    for s in specs {
        let _ = writeln!(o, "#define {prefix}_SPEC_{} (({}){})", to_upper_snake(&s.name), s.ty.c(), lit(s.value, s.ty));
    }
}

fn gen_enum(o: &mut String, e: &EnumIr) {
    let (name, prefix) = (&e.name, to_upper_snake(&e.name));
    let _ = writeln!(o, "\ntypedef enum {name} {{");
    for (v, val) in &e.variants {
        let _ = writeln!(o, "    {prefix}_{} = {val},", to_upper_snake(v));
    }
    let _ = writeln!(o, "}} {name};\n");
    let _ = writeln!(o, "static inline bool {name}_is_valid(uint64_t v) {{\n    switch (v) {{");
    for (_, val) in &e.variants {
        let _ = writeln!(o, "    case {val}u:");
    }
    let _ = writeln!(o, "        return true;\n    default:\n        return false;\n    }}\n}}");
}

fn field_ty(model: &Model, f: &FieldIr) -> String {
    match f.ty {
        FieldTy::Bool => "bool".into(),
        FieldTy::Uint(t) => t.c().into(),
        FieldTy::Sint(t) => t.c_signed().into(),
        FieldTy::Enum(i) => model.enums[i].name.clone(),
    }
}

/// Byte index expression: absolute for fixed defs, `off + n` for generic ones.
fn at(generic: bool, b: usize) -> String {
    match (generic, b) {
        (false, b) => b.to_string(),
        (true, 0) => "off".into(),
        (true, b) => format!("off + {b}u"),
    }
}

fn write_chunk(c: &Chunk, b: &str) -> String {
    let v = if c.vshift == 0 { "v".to_string() } else { format!("(v >> {})", c.vshift) };
    let mut bits = format!("(uint8_t){v}");
    if c.mask != 0xFF {
        bits = format!("({bits} & 0x{:02X}u)", c.mask);
    }
    if c.shift != 0 {
        bits = format!("({bits} << {})", c.shift);
    }
    let clear = !(c.mask << c.shift);
    if clear == 0 {
        format!("buf[{b}] = {bits};")
    } else {
        format!("buf[{b}] = (uint8_t)((buf[{b}] & 0x{clear:02X}u) | {bits});")
    }
}

fn read_chunk(c: &Chunk, b: &str) -> String {
    let mut e = format!("buf[{b}]");
    if c.shift != 0 {
        e = format!("({e} >> {})", c.shift);
    }
    if c.mask != 0xFF {
        e = format!("({e} & 0x{:02X}u)", c.mask);
    }
    e = format!("(uint64_t){e}");
    if c.vshift != 0 {
        e = format!("({e} << {})", c.vshift);
    }
    e
}

fn gen_def(o: &mut String, model: &Model, d: &DefIr) {
    let (name, macro_) = (&d.name, to_upper_snake(&d.name));
    let g = d.generic;
    if g {
        let _ = writeln!(o, "\n/* Generic: {} byte(s), placed at a byte offset where it is used. */", d.min_len);
    } else {
        let _ = writeln!(o, "\n/* Occupies payload byte(s) {:?}. */", d.bytes);
    }
    let _ = writeln!(o, "typedef struct {name} {{");
    for f in &d.fields {
        let _ = writeln!(o, "    {} {};", field_ty(model, f), f.name);
    }
    let (suffix, off_param, off_arg, short) = if g {
        let _ = writeln!(o, "}} {name};\n\n#define {macro_}_SIZE {}u\n", d.min_len);
        ("_at", ", size_t off", ", off", format!("off > len || len - off < {macro_}_SIZE"))
    } else {
        let _ = writeln!(o, "}} {name};\n\n#define {macro_}_MIN_LEN {}u\n", d.min_len);
        ("", "", "", format!("len < {macro_}_MIN_LEN"))
    };

    let _ = writeln!(o, "/* Writes the fields into buf without bounds checks, leaving other bits untouched. */");
    let _ = writeln!(o, "static inline void {name}_write{suffix}(const {name} *m, uint8_t *buf{off_param}) {{\n    uint64_t v;");
    for f in &d.fields {
        let _ = writeln!(o, "    v = (uint64_t)m->{};", f.name);
        for c in f.chunks() {
            let _ = writeln!(o, "    {}", write_chunk(&c, &at(g, c.byte)));
        }
    }
    let _ = writeln!(o, "}}\n");

    let _ = writeln!(o, "static inline int {name}_encode{suffix}(const {name} *m, uint8_t *buf, size_t len{off_param}) {{");
    let _ = writeln!(o, "    if ({short}) return PROTO_C_ERR_SHORT_BUFFER;");
    let _ = writeln!(o, "    {name}_write{suffix}(m, buf{off_arg});\n    return PROTO_C_OK;\n}}\n");

    let _ = writeln!(o, "static inline int {name}_decode{suffix}({name} *m, const uint8_t *buf, size_t len{off_param}) {{\n    uint64_t v;");
    let _ = writeln!(o, "    if ({short}) return PROTO_C_ERR_SHORT_BUFFER;");
    for f in &d.fields {
        let raw = f.chunks().iter().map(|c| read_chunk(c, &at(g, c.byte))).collect::<Vec<_>>().join(" | ");
        let _ = writeln!(o, "    v = {raw};");
        match f.ty {
            FieldTy::Bool => {
                let _ = writeln!(o, "    m->{} = (v != 0);", f.name);
            }
            FieldTy::Uint(t) => {
                let _ = writeln!(o, "    m->{} = ({})v;", f.name, t.c());
            }
            FieldTy::Sint(t) => {
                // Portable sign extension: no signed shifts or out-of-range conversions.
                let lit = |x: u64| if x > u64::from(u32::MAX) { format!("0x{x:X}ULL") } else { format!("0x{x:X}u") };
                let sign = 1u64 << (f.width - 1);
                let mask = if f.width == 64 { u64::MAX } else { (1u64 << f.width) - 1 };
                let _ = writeln!(
                    o,
                    "    m->{} = ({})((v & {}) ? -(int64_t)(~v & {}) - 1 : (int64_t)v);",
                    f.name,
                    t.c_signed(),
                    lit(sign),
                    lit(mask)
                );
            }
            FieldTy::Enum(i) => {
                let e = &model.enums[i].name;
                let _ = writeln!(o, "    if (!{e}_is_valid(v)) return PROTO_C_ERR_INVALID_ENUM;");
                let _ = writeln!(o, "    m->{} = ({e})v;", f.name);
            }
        }
    }
    let _ = writeln!(o, "    return PROTO_C_OK;\n}}");
}

/// `{macro_}_ID_*` / `_EXTENDED` defines and a `fn_name(id, extended, data, len)` check.
fn gen_matches(o: &mut String, f: &FilterIr, macro_: &str, fn_name: &str) {
    let _ = writeln!(o, "/* Exact id bits: (id & {macro_}_ID_MASK) == {macro_}_ID_MATCH (id ranges excluded) */");
    let _ = writeln!(o, "#define {macro_}_ID_MASK 0x{:X}u", f.id_mask);
    let _ = writeln!(o, "#define {macro_}_ID_MATCH 0x{:X}u", f.id_match);
    let terms = f.id_terms();
    let list = terms.iter().map(|(m, v)| format!("{{0x{m:X}u, 0x{v:X}u}}")).collect::<Vec<_>>().join(", ");
    let _ = writeln!(o, "/* Hardware acceptance filter: {{mask, match}} pairs, one per filter slot; together exact.");
    let _ = writeln!(o, "   Use as: static const uint32_t terms[][2] = {macro_}_ID_TERMS; */");
    let _ = writeln!(o, "#define {macro_}_ID_TERM_COUNT {}u", terms.len());
    let _ = writeln!(o, "#define {macro_}_ID_TERMS {{ {list} }}");
    if let Some(ext) = f.ext {
        let _ = writeln!(o, "/* Required id type: 1 = extended (29-bit), 0 = standard (11-bit) */");
        let _ = writeln!(o, "#define {macro_}_EXTENDED {}", u8::from(ext));
    }
    let _ = writeln!(o, "\nstatic inline bool {fn_name}(uint32_t id, bool extended, const uint8_t *data, size_t len) {{");
    match f.ext {
        Some(true) => {
            let _ = writeln!(o, "    if (!extended) return false;");
        }
        Some(false) => {
            let _ = writeln!(o, "    if (extended) return false;");
        }
        None => {
            let _ = writeln!(o, "    (void)extended;");
        }
    }
    if f.id_mask != 0 {
        let _ = writeln!(o, "    if ((id & {macro_}_ID_MASK) != {macro_}_ID_MATCH) return false;");
    } else if f.id_ranges.is_empty() {
        let _ = writeln!(o, "    (void)id;");
    }
    for r in &f.id_ranges {
        let field = if r.start == 0 { format!("(id & 0x{:X}u)", r.mask()) } else { format!("((id >> {}) & 0x{:X}u)", r.start, r.mask()) };
        if r.lo > 0 {
            let _ = writeln!(o, "    if ({field} < {}u) return false;", r.lo);
        }
        if r.hi < r.mask() {
            let _ = writeln!(o, "    if ({field} > {}u) return false;", r.hi);
        }
    }
    if f.data_len() == 0 {
        let _ = writeln!(o, "    (void)data;\n    (void)len;");
    } else {
        let _ = writeln!(o, "    if (len < {}u) return false;", f.data_len());
        for (i, (m, v)) in f.data_mask.iter().zip(&f.data_match).enumerate().filter(|(_, (m, _))| **m != 0) {
            let _ = writeln!(o, "    if ((data[{i}] & 0x{m:02X}u) != 0x{v:02X}u) return false;");
        }
    }
    let _ = writeln!(o, "    return true;\n}}\n");
}

fn stamp_lines(f: &FilterIr) -> String {
    let mut o = String::new();
    for (i, (m, v)) in f.data_mask.iter().zip(&f.data_match).enumerate().filter(|(_, (m, _))| **m != 0) {
        if *m == 0xFF {
            let _ = writeln!(o, "    buf[{i}] = 0x{v:02X}u;");
        } else {
            let _ = writeln!(o, "    buf[{i}] = (uint8_t)((buf[{i}] & 0x{:02X}u) | 0x{v:02X}u);", !m);
        }
    }
    o
}

fn gen_frame(o: &mut String, f: &FrameIr, model: &Model) {
    let (name, macro_) = (&f.name, to_upper_snake(&f.name));
    let _ = writeln!(o, "\n#define {macro_}_SIZE {}u", f.size);
    let _ = writeln!(o, "#define {macro_}_IS_FD {}", u8::from(f.fd));
    let _ = writeln!(o, "\ntypedef struct {name} {{");
    for m in &f.members {
        let _ = writeln!(o, "    {} {};", model.defs[m.def].name, m.field);
    }
    let _ = writeln!(o, "}} {name};\n");

    if let Some(flt) = &f.filter {
        gen_matches(o, flt, &format!("{macro_}_FILTER"), &format!("{name}_matches"));
    }

    let _ = writeln!(o, "/* Writes members (and filter data bits) without bounds checks or zeroing. */");
    let _ = writeln!(o, "static inline void {name}_write(const {name} *m, uint8_t *buf) {{");
    for m in &f.members {
        let _ = writeln!(o, "    {}", write_call(model, Slot::Def(m.def, m.at), &format!("&m->{}", m.field)));
    }
    if let Some(flt) = &f.filter {
        o.push_str(&stamp_lines(flt));
    }
    let _ = writeln!(o, "}}\n");

    let _ = writeln!(o, "/* Zeroes buf[0..SIZE) and writes the payload. */");
    let _ = writeln!(o, "static inline int {name}_encode(const {name} *m, uint8_t *buf, size_t len) {{\n    size_t i;");
    let _ = writeln!(o, "    if (len < {macro_}_SIZE) return PROTO_C_ERR_SHORT_BUFFER;");
    let _ = writeln!(o, "    for (i = 0; i < {macro_}_SIZE; ++i) buf[i] = 0;");
    let _ = writeln!(o, "    {name}_write(m, buf);\n    return PROTO_C_OK;\n}}\n");

    let _ = writeln!(o, "static inline int {name}_decode({name} *m, const uint8_t *buf, size_t len) {{\n    int rc;");
    let _ = writeln!(o, "    if (len < {macro_}_SIZE) return PROTO_C_ERR_SHORT_BUFFER;");
    for m in &f.members {
        let call = decode_call(model, Slot::Def(m.def, m.at), &format!("&m->{}", m.field), "buf");
        let _ = writeln!(o, "    rc = {call};\n    if (rc != PROTO_C_OK) return rc;");
    }
    let _ = writeln!(o, "    return PROTO_C_OK;\n}}");
}

fn slot_ty(model: &Model, slot: Slot) -> String {
    match slot {
        Slot::Prim(p, _) => p.c().into(),
        Slot::Def(d, _) => model.defs[d].name.clone(),
        Slot::Frame(f) => model.frames[f].name.clone(),
    }
}

/// Statement writing a def/frame slot from pointer `src` into `buf`.
fn write_call(model: &Model, slot: Slot, src: &str) -> String {
    let ty = slot_ty(model, slot);
    match slot {
        Slot::Def(d, at) if model.defs[d].generic => format!("{ty}_write_at({src}, buf, {at}u);"),
        _ => format!("{ty}_write({src}, buf);"),
    }
}

/// Call decoding a def/frame slot into pointer `dst`; returns a status code.
fn decode_call(model: &Model, slot: Slot, dst: &str, buf: &str) -> String {
    let ty = slot_ty(model, slot);
    match slot {
        Slot::Def(d, at) if model.defs[d].generic => format!("{ty}_decode_at({dst}, {buf}, len, {at}u)"),
        _ => format!("{ty}_decode({dst}, {buf}, len)"),
    }
}

fn unsigned_of(p: Prim) -> &'static str {
    match p.size() {
        1 => "uint8_t",
        2 => "uint16_t",
        4 => "uint32_t",
        _ => "uint64_t",
    }
}

fn store_prim(p: Prim, src: &str, off: usize, big: bool) -> String {
    let at = |i: usize| if big { off + p.size() - 1 - i } else { off + i };
    let byte = |i: usize, u: &str| {
        if i == 0 {
            format!("    buf[{}] = (uint8_t){u};\n", at(i))
        } else {
            format!("    buf[{}] = (uint8_t)({u} >> {});\n", at(i), 8 * i)
        }
    };
    match p {
        Prim::Bool => format!("    buf[{off}] = (uint8_t)({src} ? 1u : 0u);\n"),
        Prim::F32 | Prim::F64 => {
            let (f, u) = if p == Prim::F32 { ("float", "uint32_t") } else { ("double", "uint64_t") };
            let mut s = format!("    {{\n        union {{ {f} f; {u} u; }} cv;\n        cv.f = {src};\n");
            for i in 0..p.size() {
                s.push_str("    ");
                s.push_str(&byte(i, "cv.u"));
            }
            s + "    }\n"
        }
        _ => {
            let u = format!("(uint64_t)({src})");
            (0..p.size()).map(|i| byte(i, &u)).collect()
        }
    }
}

fn load_prim(p: Prim, buf: &str, off: usize, big: bool, dst: &str) -> String {
    let at = |i: usize| if big { off + p.size() - 1 - i } else { off + i };
    let raw = (0..p.size())
        .map(|i| if i == 0 { format!("(uint64_t){buf}[{}]", at(i)) } else { format!("((uint64_t){buf}[{}] << {})", at(i), 8 * i) })
        .collect::<Vec<_>>()
        .join(" | ");
    match p {
        Prim::Bool => format!("    {dst} = ({buf}[{off}] != 0);\n"),
        Prim::F32 | Prim::F64 => {
            let (f, u) = if p == Prim::F32 { ("float", "uint32_t") } else { ("double", "uint64_t") };
            format!("    {{\n        union {{ {f} f; {u} u; }} cv;\n        cv.u = ({u})({raw});\n        {dst} = cv.f;\n    }}\n")
        }
        _ if p.is_signed() => format!("    {dst} = ({})({})({raw});\n", p.c(), unsigned_of(p)),
        _ => format!("    {dst} = ({})({raw});\n", p.c()),
    }
}

fn gen_fn(o: &mut String, f: &FnIr, model: &Model) {
    let (name, macro_) = (&f.name, to_upper_snake(&f.name));
    let req = format!("{name}Request");
    let _ = writeln!(o, "\n/* ---- fn {name} ---- */");
    let _ = writeln!(o, "#define {macro_}_REQUEST_SIZE {}u", f.req_size);
    let _ = writeln!(o, "#define {macro_}_IS_FD {}", u8::from(f.fd));

    if !f.params.is_empty() {
        let _ = writeln!(o, "\ntypedef struct {req} {{");
        for p in &f.params {
            let _ = writeln!(o, "    {} {};", slot_ty(model, p.slot), p.name);
        }
        let _ = writeln!(o, "}} {req};\n");

        let _ = writeln!(o, "static inline int {req}_encode(const {req} *m, uint8_t *buf, size_t len) {{\n    size_t i;");
        let _ = writeln!(o, "    if (len < {macro_}_REQUEST_SIZE) return PROTO_C_ERR_SHORT_BUFFER;");
        let _ = writeln!(o, "    for (i = 0; i < {macro_}_REQUEST_SIZE; ++i) buf[i] = 0;");
        for p in &f.params {
            match p.slot {
                Slot::Prim(t, off) => o.push_str(&store_prim(t, &format!("m->{}", p.name), off, f.big)),
                _ => {
                    let _ = writeln!(o, "    {}", write_call(model, p.slot, &format!("&m->{}", p.name)));
                }
            }
        }
        let _ = writeln!(o, "    return PROTO_C_OK;\n}}\n");

        let needs_rc = f.params.iter().any(|p| !matches!(p.slot, Slot::Prim(..)));
        let _ = writeln!(o, "static inline int {req}_decode({req} *m, const uint8_t *buf, size_t len) {{");
        if needs_rc {
            let _ = writeln!(o, "    int rc;");
        }
        let _ = writeln!(o, "    if (len < {macro_}_REQUEST_SIZE) return PROTO_C_ERR_SHORT_BUFFER;");
        for p in &f.params {
            match p.slot {
                Slot::Prim(t, off) => o.push_str(&load_prim(t, "buf", off, f.big, &format!("m->{}", p.name))),
                _ => {
                    let call = decode_call(model, p.slot, &format!("&m->{}", p.name), "buf");
                    let _ = writeln!(o, "    rc = {call};\n    if (rc != PROTO_C_OK) return rc;");
                }
            }
        }
        let _ = writeln!(o, "    return PROTO_C_OK;\n}}");
    }

    let (Some(ret), Some(rsp)) = (f.ret, &f.rsp) else { return };
    let ret_ty = slot_ty(model, ret);
    let _ = writeln!(o, "\n#define {macro_}_RSP_SIZE {}u", f.rsp_size);
    gen_matches(o, rsp, &format!("{macro_}_RSP"), &format!("{name}_is_response"));

    let _ = writeln!(o, "static inline int {name}_decode_response({ret_ty} *out, const uint8_t *data, size_t len) {{");
    let _ = writeln!(o, "    if (len < {macro_}_RSP_SIZE) return PROTO_C_ERR_SHORT_BUFFER;");
    match ret {
        Slot::Prim(t, off) => {
            o.push_str(&load_prim(t, "data", off, f.big, "*out"));
            let _ = writeln!(o, "    return PROTO_C_OK;");
        }
        _ => {
            let _ = writeln!(o, "    return {};", decode_call(model, ret, "out", "data"));
        }
    }
    let _ = writeln!(o, "}}\n");

    let value = if matches!(ret, Slot::Prim(..)) { format!("{ret_ty} value") } else { format!("const {ret_ty} *value") };
    let _ = writeln!(o, "/* Zeroes buf[0..RSP_SIZE), writes value and the filter's data bits. */");
    let _ = writeln!(o, "static inline int {name}_encode_response({value}, uint8_t *buf, size_t len) {{\n    size_t i;");
    let _ = writeln!(o, "    if (len < {macro_}_RSP_SIZE) return PROTO_C_ERR_SHORT_BUFFER;");
    let _ = writeln!(o, "    for (i = 0; i < {macro_}_RSP_SIZE; ++i) buf[i] = 0;");
    match ret {
        Slot::Prim(t, off) => o.push_str(&store_prim(t, "value", off, f.big)),
        _ => {
            let _ = writeln!(o, "    {}", write_call(model, ret, "value"));
        }
    }
    o.push_str(&stamp_lines(rsp));
    let _ = writeln!(o, "    return PROTO_C_OK;\n}}");
}
