//! Rust code generator. Output is `no_std` friendly and usable via `mod` or `include!`.

use std::fmt::Write;

use super::Layout;
use crate::tools::{
    ast::Literal,
    resolve::{Chunk, DefIr, EnumIr, FieldIr, FieldTy, FilterIr, FnIr, FrameIr, Model, Prim, Slot},
    syntax::{to_pascal, to_upper_snake},
};

/// `mod.rs` of a package: shared prelude plus one module per file.
pub fn package_mod(pkg: &str, modules: &[String]) -> String {
    let mut o = format!("// @generated by proto_c for package `{pkg}`. Do not edit.\n\n{PRELUDE}\n");
    for m in modules {
        let _ = writeln!(o, "pub mod {m};");
    }
    o
}

pub fn generate(model: &Model, source: &str, layout: &Layout) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "// @generated by proto_c from `{source}`. Do not edit.\n");
    match layout {
        Layout::Standalone => o.push_str(PRELUDE),
        Layout::Unit { rust_uses, .. } => {
            o.push_str("#[allow(unused_imports)]\nuse super::*;\n");
            for u in *rust_uses {
                let _ = writeln!(o, "#[allow(unused_imports)]\nuse super::{u}::*;");
            }
        }
    }
    gen_specs(&mut o, model);
    for e in model.enums.iter().filter(|e| !e.external) {
        gen_enum(&mut o, e);
    }
    for d in model.defs.iter().filter(|d| !d.external) {
        gen_def(&mut o, model, d);
    }
    for f in model.frames.iter().filter(|f| !f.external) {
        gen_frame(&mut o, model, f);
    }
    for f in model.fns.iter().filter(|f| !f.external) {
        gen_fn(&mut o, model, f);
    }
    o
}

const PRELUDE: &str = r#"#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CodecError {
    /// The buffer is shorter than the payload layout requires.
    BufferTooShort { expected: usize, actual: usize },
    /// A field holds a value that is not a variant of its enum type.
    InvalidEnum { field: &'static str, value: u64 },
}

impl core::fmt::Display for CodecError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::BufferTooShort { expected, actual } => {
                write!(f, "buffer too short: expected {expected} bytes, got {actual}")
            }
            Self::InvalidEnum { field, value } => write!(f, "invalid value {value} for field `{field}`"),
        }
    }
}

#[inline]
fn check_len(buf_len: usize, expected: usize) -> Result<(), CodecError> {
    if buf_len < expected {
        return Err(CodecError::BufferTooShort { expected, actual: buf_len });
    }
    Ok(())
}
"#;

fn lit(l: Literal, ty: Prim) -> String {
    match l {
        Literal::Int(v) => v.to_string(),
        Literal::Float(f) if ty == Prim::F32 => format!("{:?}", f as f32),
        Literal::Float(f) => format!("{f:?}"),
        Literal::Bool(b) => b.to_string(),
    }
}

fn gen_specs(o: &mut String, model: &Model) {
    let specs: Vec<_> = model.specs.iter().filter(|s| !s.external).collect();
    if specs.is_empty() {
        return;
    }
    let _ = writeln!(o, "\npub mod spec {{");
    for s in specs {
        let _ = writeln!(o, "    pub const {}: {} = {};", to_upper_snake(&s.name), s.ty.rust(), lit(s.value, s.ty));
    }
    let _ = writeln!(o, "}}");
}

fn gen_enum(o: &mut String, e: &EnumIr) {
    let (name, repr) = (&e.name, e.repr.rust());
    let _ = writeln!(o, "\n#[repr({repr})]\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum {name} {{");
    for (v, val) in &e.variants {
        let _ = writeln!(o, "    {} = {val},", to_pascal(v));
    }
    let _ = writeln!(o, "}}\n\nimpl {name} {{");
    let _ = writeln!(o, "    pub const fn from_raw(value: u64) -> Option<Self> {{\n        match value {{");
    for (v, val) in &e.variants {
        let _ = writeln!(o, "            {val} => Some(Self::{}),", to_pascal(v));
    }
    let _ = writeln!(o, "            _ => None,\n        }}\n    }}\n}}\n");
    let default = to_pascal(&e.variants[e.default].0);
    let _ = writeln!(
        o,
        "impl Default for {name} {{\n    fn default() -> Self {{\n        Self::{default}\n    }}\n}}\n\n\
         impl From<{name}> for {repr} {{\n    fn from(v: {name}) -> Self {{\n        v as {repr}\n    }}\n}}\n\n\
         impl TryFrom<{repr}> for {name} {{\n    type Error = {repr};\n\n    \
         fn try_from(v: {repr}) -> Result<Self, {repr}> {{\n        Self::from_raw(v as u64).ok_or(v)\n    }}\n}}"
    );
}

fn field_ty(model: &Model, f: &FieldIr) -> String {
    match f.ty {
        FieldTy::Bool => "bool".into(),
        FieldTy::Uint(t) => t.rust().into(),
        FieldTy::Sint(t) => t.rust_signed().into(),
        FieldTy::Enum(i) => model.enums[i].name.clone(),
    }
}

/// Byte index expression: absolute for fixed defs, `off + n` for generic ones.
fn at(generic: bool, b: usize) -> String {
    match (generic, b) {
        (false, b) => b.to_string(),
        (true, 0) => "off".into(),
        (true, b) => format!("off + {b}"),
    }
}

fn gen_def(o: &mut String, model: &Model, d: &DefIr) {
    let name = &d.name;
    let g = d.generic;
    let _ = writeln!(o, "\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]\npub struct {name} {{");
    for f in &d.fields {
        let _ = writeln!(o, "    pub {}: {},", f.name, field_ty(model, f));
    }
    let _ = writeln!(o, "}}\n\nimpl {name} {{");
    let (suffix, off_param, off_arg, need) = if g {
        let _ = writeln!(o, "    /// Size in bytes; placed at a byte offset where it is used.\n    pub const SIZE: usize = {};\n", d.min_len);
        ("_at", ", off: usize", ", off", "off.saturating_add(Self::SIZE)")
    } else {
        let bytes = d.bytes.iter().map(|b| b.to_string()).collect::<Vec<_>>().join(", ");
        let _ = writeln!(o, "    /// Payload bytes occupied by this def.\n    pub const BYTES: &'static [usize] = &[{bytes}];");
        let _ = writeln!(o, "    /// Minimum payload length that contains this def.\n    pub const MIN_LEN: usize = {};\n", d.min_len);
        ("", "", "", "Self::MIN_LEN")
    };

    let _ = writeln!(o, "    /// Writes the fields into `buf`, leaving bits of other defs untouched.");
    let _ = writeln!(o, "    pub fn encode{suffix}(&self, buf: &mut [u8]{off_param}) -> Result<(), CodecError> {{");
    let _ = writeln!(o, "        check_len(buf.len(), {need})?;\n        self.write{suffix}(buf{off_arg});\n        Ok(())\n    }}\n");

    let _ = writeln!(o, "    pub fn decode{suffix}(buf: &[u8]{off_param}) -> Result<Self, CodecError> {{");
    let _ = writeln!(o, "        check_len(buf.len(), {need})?;\n        Ok(Self {{");
    for f in &d.fields {
        let _ = writeln!(o, "            {}: {},", f.name, decode_expr(model, f, g));
    }
    let _ = writeln!(o, "        }})\n    }}\n");

    let _ = writeln!(o, "    #[inline]\n    pub(crate) fn write{suffix}(&self, buf: &mut [u8]{off_param}) {{");
    for f in &d.fields {
        let _ = writeln!(o, "        let v = self.{} as u64;", f.name);
        for c in f.chunks() {
            let _ = writeln!(o, "        {}", write_chunk(&c, &at(g, c.byte)));
        }
    }
    let _ = writeln!(o, "    }}\n}}");
}

fn write_chunk(c: &Chunk, b: &str) -> String {
    let v = if c.vshift == 0 { "v".to_string() } else { format!("(v >> {})", c.vshift) };
    let cast = format!("{v} as u8");
    let bits = match (c.mask != 0xFF, c.shift != 0) {
        (false, false) => cast,
        (true, false) => format!("({cast}) & 0x{:02X}", c.mask),
        (true, true) => format!("(({cast}) & 0x{:02X}) << {}", c.mask, c.shift),
        (false, true) => format!("({cast}) << {}", c.shift),
    };
    let clear = !(c.mask << c.shift);
    if clear == 0 {
        format!("buf[{b}] = {bits};")
    } else {
        format!("buf[{b}] = (buf[{b}] & 0x{clear:02X}) | ({bits});")
    }
}

/// Minimal-parenthesis expression so the output is clean under `#![deny(warnings)]`.
fn read_chunk(c: &Chunk, b: &str) -> String {
    let mut e = format!("buf[{b}]");
    let mut compound = false;
    if c.shift != 0 {
        e = format!("{e} >> {}", c.shift);
        compound = true;
    }
    if c.mask != 0xFF {
        e = if compound { format!("({e}) & 0x{:02X}", c.mask) } else { format!("{e} & 0x{:02X}", c.mask) };
        compound = true;
    }
    e = if compound { format!("({e}) as u64") } else { format!("{e} as u64") };
    if c.vshift != 0 {
        e = format!("({e}) << {}", c.vshift);
    }
    e
}

fn decode_expr(model: &Model, f: &FieldIr, generic: bool) -> String {
    let chunks = f.chunks();
    let raw = if chunks.len() == 1 {
        read_chunk(&chunks[0], &at(generic, chunks[0].byte))
    } else {
        chunks.iter().map(|c| format!("({})", read_chunk(c, &at(generic, c.byte)))).collect::<Vec<_>>().join(" | ")
    };
    match f.ty {
        FieldTy::Bool => format!("{raw} != 0"),
        FieldTy::Uint(t) => format!("({raw}) as {}", t.rust()),
        FieldTy::Sint(t) if f.width == 64 => format!("({raw}) as {}", t.rust_signed()),
        FieldTy::Sint(t) => format!(
            "{{\n                let v = {raw};\n                ((v << {s}) as i64 >> {s}) as {}\n            }}",
            t.rust_signed(),
            s = 64 - f.width
        ),
        FieldTy::Enum(i) => format!(
            "{{\n                let v = {raw};\n                {}::from_raw(v).ok_or(CodecError::InvalidEnum {{ field: \"{}\", value: v }})?\n            }}",
            model.enums[i].name, f.name
        ),
    }
}

/// `{prefix}ID_*` consts and a `fn_name(id, extended, data)` check.
fn gen_matches(o: &mut String, f: &FilterIr, prefix: &str, fn_name: &str) {
    let _ = writeln!(o, "    /// Exact id bits: `(id & {prefix}ID_MASK) == {prefix}ID_MATCH` (id ranges excluded).");
    let _ = writeln!(o, "    pub const {prefix}ID_MASK: u32 = 0x{:X};", f.id_mask);
    let _ = writeln!(o, "    pub const {prefix}ID_MATCH: u32 = 0x{:X};", f.id_match);
    let terms = f.id_terms().iter().map(|(m, v)| format!("(0x{m:X}, 0x{v:X})")).collect::<Vec<_>>().join(", ");
    let _ = writeln!(o, "    /// Hardware acceptance filter: (mask, match) pairs, one per filter slot; together exact.");
    let _ = writeln!(o, "    pub const {prefix}ID_TERMS: &'static [(u32, u32)] = &[{terms}];");
    let _ = writeln!(o, "    /// Required id type: `Some(true)` extended (29-bit), `Some(false)` standard (11-bit).");
    let _ = writeln!(o, "    pub const {prefix}EXTENDED: Option<bool> = {:?};\n", f.ext);
    let mut conds = Vec::new();
    match f.ext {
        Some(true) => conds.push("extended".to_string()),
        Some(false) => conds.push("!extended".to_string()),
        None => {}
    }
    if f.id_mask != 0 {
        conds.push(format!("(id & Self::{prefix}ID_MASK) == Self::{prefix}ID_MATCH"));
    }
    for r in &f.id_ranges {
        let field = if r.start == 0 { format!("(id & 0x{:X})", r.mask()) } else { format!("((id >> {}) & 0x{:X})", r.start, r.mask()) };
        if r.lo > 0 {
            conds.push(format!("{field} >= {}", r.lo));
        }
        if r.hi < r.mask() {
            conds.push(format!("{field} <= {}", r.hi));
        }
    }
    if f.data_len() > 0 {
        conds.push(format!("data.len() >= {}", f.data_len()));
    }
    for (i, (m, v)) in f.data_mask.iter().zip(&f.data_match).enumerate().filter(|(_, (m, _))| **m != 0) {
        conds.push(format!("(data[{i}] & 0x{m:02X}) == 0x{v:02X}"));
    }
    let id = if f.id_mask != 0 || !f.id_ranges.is_empty() { "id" } else { "_id" };
    let extended = if f.ext.is_some() { "extended" } else { "_extended" };
    let data = if f.data_len() > 0 { "data" } else { "_data" };
    let body = if conds.is_empty() { "true".to_string() } else { conds.join("\n            && ") };
    let _ = writeln!(o, "    /// True if a received frame passes this filter.");
    let _ = writeln!(o, "    pub fn {fn_name}({id}: u32, {extended}: bool, {data}: &[u8]) -> bool {{\n        {body}\n    }}\n");
}

fn stamp_lines(f: &FilterIr, indent: &str) -> String {
    let mut o = String::new();
    for (i, (m, v)) in f.data_mask.iter().zip(&f.data_match).enumerate().filter(|(_, (m, _))| **m != 0) {
        if *m == 0xFF {
            let _ = writeln!(o, "{indent}buf[{i}] = 0x{v:02X};");
        } else {
            let _ = writeln!(o, "{indent}buf[{i}] = (buf[{i}] & 0x{:02X}) | 0x{v:02X};", !m);
        }
    }
    o
}

fn gen_frame(o: &mut String, model: &Model, f: &FrameIr) {
    let name = &f.name;
    let _ = writeln!(o, "\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]\npub struct {name} {{");
    for m in &f.members {
        let _ = writeln!(o, "    pub {}: {},", m.field, model.defs[m.def].name);
    }
    let _ = writeln!(o, "}}\n\nimpl {name} {{");
    let _ = writeln!(o, "    pub const SIZE: usize = {};", f.size);
    let _ = writeln!(o, "    pub const FD: bool = {};\n", f.fd);
    if let Some(flt) = &f.filter {
        gen_matches(o, flt, "FILTER_", "matches");
    }

    let _ = writeln!(o, "    pub fn to_bytes(&self) -> [u8; {}] {{", f.size);
    let _ = writeln!(o, "        let mut buf = [0u8; {}];\n        self.write(&mut buf);\n        buf\n    }}\n", f.size);

    let _ = writeln!(o, "    /// Zeroes `buf[..SIZE]` and writes the frame payload into it.");
    let _ = writeln!(o, "    pub fn encode(&self, buf: &mut [u8]) -> Result<usize, CodecError> {{");
    let _ = writeln!(o, "        check_len(buf.len(), Self::SIZE)?;");
    let _ = writeln!(o, "        buf[..Self::SIZE].copy_from_slice(&self.to_bytes());\n        Ok(Self::SIZE)\n    }}\n");

    let _ = writeln!(o, "    pub fn decode(buf: &[u8]) -> Result<Self, CodecError> {{");
    let _ = writeln!(o, "        check_len(buf.len(), Self::SIZE)?;\n        Ok(Self {{");
    for m in &f.members {
        let _ = writeln!(o, "            {}: {}?,", m.field, decode_call(model, Slot::Def(m.def, m.at), "buf"));
    }
    let _ = writeln!(o, "        }})\n    }}\n");

    let _ = writeln!(o, "    #[inline]\n    pub(crate) fn write(&self, buf: &mut [u8]) {{");
    for m in &f.members {
        let _ = writeln!(o, "        {}", write_call(model, Slot::Def(m.def, m.at), &format!("self.{}", m.field)));
    }
    if let Some(flt) = &f.filter {
        o.push_str(&stamp_lines(flt, "        "));
    }
    let _ = writeln!(o, "    }}\n}}");
}

fn slot_ty(model: &Model, slot: Slot) -> String {
    match slot {
        Slot::Prim(p, _) => p.rust().into(),
        Slot::Def(d, _) => model.defs[d].name.clone(),
        Slot::Frame(f) => model.frames[f].name.clone(),
    }
}

/// Statement writing a def/frame slot from `src` into `buf`.
fn write_call(model: &Model, slot: Slot, src: &str) -> String {
    match slot {
        Slot::Def(d, at) if model.defs[d].generic => format!("{src}.write_at(buf, {at});"),
        _ => format!("{src}.write(buf);"),
    }
}

/// `Result` expression decoding a def/frame slot from `buf`.
fn decode_call(model: &Model, slot: Slot, buf: &str) -> String {
    let ty = slot_ty(model, slot);
    match slot {
        Slot::Def(d, at) if model.defs[d].generic => format!("{ty}::decode_at({buf}, {at})"),
        _ => format!("{ty}::decode({buf})"),
    }
}

fn store_prim(p: Prim, src: &str, off: usize, big: bool) -> String {
    let order = if big { "be" } else { "le" };
    match p {
        Prim::Bool => format!("buf[{off}] = {src} as u8;"),
        Prim::U8 => format!("buf[{off}] = {src};"),
        Prim::I8 => format!("buf[{off}] = {src} as u8;"),
        _ => format!("buf[{off}..{}].copy_from_slice(&{src}.to_{order}_bytes());", off + p.size()),
    }
}

fn load_prim(p: Prim, buf: &str, off: usize, big: bool) -> String {
    let order = if big { "be" } else { "le" };
    match p {
        Prim::Bool => format!("{buf}[{off}] != 0"),
        Prim::U8 => format!("{buf}[{off}]"),
        _ => {
            let bytes = (off..off + p.size()).map(|i| format!("{buf}[{i}]")).collect::<Vec<_>>().join(", ");
            format!("{}::from_{order}_bytes([{bytes}])", p.rust())
        }
    }
}

fn gen_fn(o: &mut String, model: &Model, f: &FnIr) {
    let req = format!("{}Request", f.name);
    let has_float = f.params.iter().any(|p| matches!(p.slot, Slot::Prim(t, _) if t.is_float()));
    let derives = if has_float { "Debug, Clone, Copy, PartialEq, Default" } else { "Debug, Clone, Copy, PartialEq, Eq, Default" };
    let _ = write!(o, "\n/// Request payload of `{}`.\n#[derive({derives})]\npub struct {req} {{", f.name);
    if !f.params.is_empty() {
        o.push('\n');
    }
    for p in &f.params {
        let _ = writeln!(o, "    pub {}: {},", p.name, slot_ty(model, p.slot));
    }
    let _ = writeln!(o, "}}\n\nimpl {req} {{");
    let _ = writeln!(o, "    pub const SIZE: usize = {};\n    pub const FD: bool = {};\n", f.req_size, f.fd);
    let _ = writeln!(o, "    pub fn to_bytes(&self) -> [u8; {}] {{", f.req_size);
    let _ = writeln!(o, "        let mut buf = [0u8; {}];\n        self.write(&mut buf);\n        buf\n    }}\n", f.req_size);
    let _ = writeln!(o, "    pub fn encode(&self, buf: &mut [u8]) -> Result<usize, CodecError> {{");
    let _ = writeln!(o, "        check_len(buf.len(), Self::SIZE)?;");
    let _ = writeln!(o, "        buf[..Self::SIZE].copy_from_slice(&self.to_bytes());\n        Ok(Self::SIZE)\n    }}\n");
    let _ = writeln!(o, "    pub fn decode(buf: &[u8]) -> Result<Self, CodecError> {{");
    let _ = write!(o, "        check_len(buf.len(), Self::SIZE)?;\n        Ok(Self {{");
    if !f.params.is_empty() {
        o.push('\n');
    }
    for p in &f.params {
        let expr = match p.slot {
            Slot::Prim(t, off) => load_prim(t, "buf", off, f.big),
            _ => format!("{}?", decode_call(model, p.slot, "buf")),
        };
        let _ = writeln!(o, "            {}: {expr},", p.name);
    }
    let indent = if f.params.is_empty() { "" } else { "        " };
    let _ = writeln!(o, "{indent}}})\n    }}\n");
    let buf = if f.params.is_empty() { "_buf" } else { "buf" };
    let _ = writeln!(o, "    fn write(&self, {buf}: &mut [u8]) {{");
    for p in &f.params {
        let line = match p.slot {
            Slot::Prim(t, off) => store_prim(t, &format!("self.{}", p.name), off, f.big),
            _ => write_call(model, p.slot, &format!("self.{}", p.name)),
        };
        let _ = writeln!(o, "        {line}");
    }
    let _ = writeln!(o, "    }}\n}}");

    let (Some(ret), Some(rsp)) = (f.ret, &f.rsp) else { return };
    let name = &f.name;
    let ret_ty = slot_ty(model, ret);
    let _ = writeln!(o, "\n/// Response side of `{name}`.\npub struct {name};\n\nimpl {name} {{");
    let _ = writeln!(o, "    pub const RSP_SIZE: usize = {};\n    pub const FD: bool = {};", f.rsp_size, f.fd);
    gen_matches(o, rsp, "RSP_", "is_response");

    let _ = writeln!(o, "    pub fn decode_response(data: &[u8]) -> Result<{ret_ty}, CodecError> {{");
    let _ = writeln!(o, "        check_len(data.len(), Self::RSP_SIZE)?;");
    match ret {
        Slot::Prim(t, off) => {
            let _ = writeln!(o, "        Ok({})", load_prim(t, "data", off, f.big));
        }
        _ => {
            let _ = writeln!(o, "        {}", decode_call(model, ret, "data"));
        }
    }
    let _ = writeln!(o, "    }}\n");

    let value_ty = if matches!(ret, Slot::Prim(..)) { ret_ty.clone() } else { format!("&{ret_ty}") };
    let _ = writeln!(o, "    /// Zeroes `buf[..RSP_SIZE]`, writes `value` and the filter's data bits.");
    let _ = writeln!(o, "    pub fn encode_response(value: {value_ty}, buf: &mut [u8]) -> Result<usize, CodecError> {{");
    let _ = writeln!(o, "        check_len(buf.len(), Self::RSP_SIZE)?;\n        buf[..Self::RSP_SIZE].fill(0);");
    match ret {
        Slot::Prim(t, off) => {
            let _ = writeln!(o, "        {}", store_prim(t, "value", off, f.big));
        }
        _ => {
            let _ = writeln!(o, "        {}", write_call(model, ret, "value"));
        }
    }
    o.push_str(&stamp_lines(rsp, "        "));
    let _ = writeln!(o, "        Ok(Self::RSP_SIZE)\n    }}\n}}");
}
